class ExternalMlModelAdapter implements RetinalModelAdapter {
  readonly adapterName = 'External Retinal ML Service';
  readonly mode = 'EXTERNAL_ML_ENDPOINT' as const;
  private readonly endpointUrl: string;

  constructor(endpointUrl: string) {
    this.endpointUrl = endpointUrl;
  }

  async analyze(input: AnalyzeRetinalImageInput): Promise<RetinaAnalysisResult> {
    const controller = new AbortController();
    const timeoutId = setTimeout(() => controller.abort(), 15000);
    try {
      const res = await fetch(`${this.endpointUrl.replace(/\/$/, '')}/predict`, {
        method: 'POST',
        headers: { 'Content-Type': 'application/json' },
        body: JSON.stringify({
          imageDataUrl: input.imageDataUrl,
          pixelStats: input.pixelStats,
        }),
        signal: controller.signal,
      });
      if (!res.ok) {
        throw new Error(`External ML backend responded with status ${res.status}`);
      }
      return (await res.json()) as RetinaAnalysisResult;
    } finally {
      clearTimeout(timeoutId);
    }
  }
}

export async function analyzeRetinalImage(
  input: AnalyzeRetinalImageInput
): Promise<RetinaAnalysisResult> {
  const externalUrl = process.env.ML_BACKEND_URL?.trim();
  if (externalUrl && input.sourceType === 'upload') {
    const adapter = new ExternalMlModelAdapter(externalUrl);
    return adapter.analyze(input);
  }
  const demoAdapter = new DemoEducationalModelAdapter();
  return demoAdapter.analyze(input);
}
